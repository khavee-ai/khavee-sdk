#!/usr/bin/env node
/**
 * Regenerates src/lipsync/vendor/* from the @met4citizen/headaudio devDependency.
 *
 * HeadAudio's worklet and model must be loaded by URL. Inlining them lets the
 * SDK create blob URLs at runtime, so consumers need no static-asset setup.
 *
 *   node scripts/vendor-headaudio.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const pkgDir = dirname(require.resolve("@met4citizen/headaudio/package.json"));
const pkg = JSON.parse(readFileSync(join(pkgDir, "package.json"), "utf8"));
const license = readFileSync(join(pkgDir, "LICENSE"), "utf8").trim();
const outDir = join(dirname(fileURLToPath(import.meta.url)), "..", "src", "lipsync", "vendor");
mkdirSync(outDir, { recursive: true });

const header = (what) =>
  `/*!\n * ${what}\n * Vendored from @met4citizen/headaudio@${pkg.version} (https://github.com/met4citizen/HeadAudio).\n * Generated by scripts/vendor-headaudio.mjs — do not edit by hand.\n *\n${license
    .split("\n")
    .map((l) => ` * ${l}`.trimEnd())
    .join("\n")}\n */\n`;

const node = readFileSync(join(pkgDir, "dist", "headaudio.min.mjs"), "utf8");
writeFileSync(
  join(outDir, "headaudio-node.ts"),
  `${header("HeadAudio AudioWorkletNode (minified ESM build).")}// @ts-nocheck\n/* eslint-disable */\n${node.trim()}\n`,
);

const worklet = readFileSync(join(pkgDir, "dist", "headworklet.min.mjs"), "utf8");
writeFileSync(
  join(outDir, "headworklet-source.ts"),
  `${header("HeadAudio worklet processor source, registered via a blob URL.")}export const HEADWORKLET_SOURCE: string = ${JSON.stringify(worklet.trim())};\n`,
);

const model = readFileSync(join(pkgDir, "dist", "model-en-mixed.bin"));
writeFileSync(
  join(outDir, "model-en-mixed.ts"),
  `${header("HeadAudio pre-trained viseme model (model-en-mixed.bin), base64.")}export const HEADAUDIO_MODEL_BYTES = ${model.length};\nexport const HEADAUDIO_MODEL_BASE64: string =\n  ${JSON.stringify(model.toString("base64"))};\n`,
);

console.log(`Vendored @met4citizen/headaudio@${pkg.version} into ${outDir}`);
